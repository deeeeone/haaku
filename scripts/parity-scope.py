#!/usr/bin/env python3
"""Emit docs/parity/SCOPE.md — the frozen in-scope endpoint set.

One row per operation in the vendored contract (`docs/parity/upstream/trakt-openapi.json`),
one line each: the contract's path, the group that owns it, the issue that group
is tracked on, and whether it is **in** the 100%-parity goal or **out** by an
owner decision (with the rationale that names its kind).

Generated, never hand-edited:

    python3 scripts/parity-scope.py           # rewrite docs/parity/SCOPE.md
    python3 scripts/parity-scope.py --check   # fail if the file is stale (CI-able)

Ownership comes from `scripts/parity-owners.py` — one source of truth for "who
owns this row", so the scope doc, the stub comments and the per-issue tables
cannot disagree.
"""
import importlib.util
import json
import sys
from pathlib import Path

# Importing the sibling script must not leave a .pyc behind: this runs as a CI
# gate, and a tracked-file diff would make `git diff --exit-code` fail on a run
# that changed nothing.
sys.dont_write_bytecode = True

ROOT = Path(__file__).resolve().parent.parent
CONTRACT = ROOT / "docs/parity/upstream/trakt-openapi.json"
OUT = ROOT / "docs/parity/SCOPE.md"

spec = importlib.util.spec_from_file_location("parity_owners", ROOT / "scripts/parity-owners.py")
po = importlib.util.module_from_spec(spec)
spec.loader.exec_module(po)


def group_label(group):
    issue, name = po.GROUP_NAME.get(group, (None, group))
    return (f"#{issue}" if issue else f"unfiled ({name})"), name


def contract_ops():
    """Every (method, path) the vendored contract publishes."""
    doc = json.loads(CONTRACT.read_text())
    ops = []
    for path, item in doc["paths"].items():
        for method in item:
            if method.lower() in ("get", "post", "put", "delete", "patch", "head", "options"):
                ops.append(f"{method.upper()} {path}")
    return ops


def render():
    manifest_rows = {(r["trakt"]): r for r in po.rows_all()}
    ops = sorted(contract_ops())
    buckets = {"in": [], "out": [], "done": []}
    for op in ops:
        row = manifest_rows.get(op)
        if row is None:
            continue  # an untracked contract op; #100's reconciler owns that count
        if row["status"] == "implemented":
            buckets["done"].append((op, row))
        elif row["status"] == "out-of-scope" and row["rationale"].startswith("decision:"):
            buckets["out"].append((op, row))
        else:
            buckets["in"].append((op, row))

    lines = []
    w = lines.append
    w("# Frozen parity scope\n")
    w("Generated by `scripts/parity-scope.py` from `docs/parity/upstream/trakt-openapi.json`")
    w("(the contract) and `docs/parity/parity.yaml` (the grades). Do not hand-edit: the")
    w("`--check` mode fails when this file and the manifest disagree.\n")
    w("**The goal, as one checkable sentence.** Every operation in the contract is served")
    w("by a real haaku handler, from real rows in our store, accepting that operation's")
    w("request schema and producing that operation's response schema, at the contract's")
    w("path (modulo our `/v1` prefix), with a real 2xx — except the recommendation/related")
    w("engine, which stays an honest `501 not_implemented` and graded `blocked-engine` by")
    w("the owner's carve-out. Done is `go run ./cmd/parity`, not a PR count.\n")
    w(f"Contract operations: **{len(ops)}**. "
      f"Not yet served (**in scope**): **{len(buckets['in'])}**. "
      f"Out by owner decision: **{len(buckets['out'])}**. "
      f"Served today: **{len(buckets['done'])}**.\n")

    w("## Out of scope (owner decisions, re-affirmed)\n")
    w("These are **recorded, not forgotten**: each is one line in this table and one row")
    w("in `parity.yaml`, so re-opening one later is a status change and a re-run, not a")
    w("re-audit. They are declined for a stated reason, never to make a number look good.\n")
    if buckets["out"]:
        w("| Contract operation | Rationale |")
        w("|---|---|")
        for op, row in sorted(buckets["out"]):
            w(f"| `{op}` | {row['rationale'].replace('|', chr(92)+'|')} |")
    else:
        w("_None._")
    w("")

    w("## In scope\n")
    w("| Contract operation | Status | Group | Owner |")
    w("|---|---|---|---|")
    for op, row in sorted(buckets["in"]):
        owner, name = group_label(row["group"])
        w(f"| `{op}` | {row['status']} | {name} | {owner} |")
    w("")

    w("## Served today\n")
    w("| Contract operation | Our path |")
    w("|---|---|")
    for op, row in sorted(buckets["done"]):
        w(f"| `{op}` | `{row['ours']}` |")
    w("")
    return "\n".join(lines) + "\n"


def main():
    text = render()
    if "--check" in sys.argv:
        current = OUT.read_text() if OUT.exists() else ""
        if current != text:
            print("docs/parity/SCOPE.md is stale — run python3 scripts/parity-scope.py")
            return 1
        print("docs/parity/SCOPE.md is current")
        return 0
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)} ({len(text.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    sys.exit(main())